import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
const context = vm.createContext({});
const products = new vm.SourceTextModule(await fs.readFile(new URL('../lib/products.js', import.meta.url), 'utf8'), { context });
await products.link(() => { throw new Error('Unexpected product dependency'); });
await products.evaluate();
const module = new vm.SourceTextModule(await fs.readFile(new URL('../lib/refreshCartPrices.js', import.meta.url), 'utf8'), { context });
await module.link(() => products);
await module.evaluate();
const refresh = module.namespace.refreshCartPrices;
const product = products.namespace.getProductById('that-booty-tho');
const gift = products.namespace.FREE_GIFT;
const updated = refresh([{id:product.id,quantity:2,price:32,originalPrice:99,name:'Old name'}, {id:gift.id,quantity:1,price:99}, {id:'removed-product',quantity:1}, {id:product.id,quantity:0}]);
assert.equal(updated.length, 2);
assert.equal(updated[0].price, product.price);
assert.equal(updated[0].quantity, 2);
assert.equal(updated[0].name, product.name);
assert.equal(updated[0].originalPrice, product.originalPrice);
assert.equal(updated[1].price, 0);
assert.equal(updated[1].originalPrice, gift.price);
assert.equal(refresh(null).length, 0);
console.log('Saved cart refresh: current catalog prices, quantities, free gift, and removed items passed.');
